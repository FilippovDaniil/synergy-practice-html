std::string renderCss(const Organization& org) {
    const std::vector<Font> fonts = allFonts(org);
    std::string css;
    css += "/* Generated by html_generator. Official font: " + org.officialFont.name + " */\n";
    css += ":root {\n  --font-main: " + fontStack(org.officialFont) + ";\n}\n";
    css += kBaseCss;
    css += "\n/* Fonts: 0 = official, 1..5 = alternatives */\n";
    for (std::size_t i = 0; i < fonts.size(); ++i) {
        css += ".font-" + std::to_string(i) + " { font-family: " + fontStack(fonts[i]) +
               "; } /* " + fonts[i].category + " */\n";
    }
    return css;
}

